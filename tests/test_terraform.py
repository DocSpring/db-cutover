import datetime
import re
from pathlib import Path

import pytest

from db_cutover.commands import terraform as tf
from db_cutover.config import TerraformLayout

BLUE = """// Generated by db_cutover_orchestrator run run-20251111-201901

resource "aws_db_instance" "rds_database" {
  identifier             = "example-app-staging-20251111201901"
  instance_class         = "db.t4g.small"
  engine                 = "postgres"
  engine_version         = "17.6"
  allocated_storage      = 30
  password               = local.db_op_fields["example_app_rds_admin_password"]
  deletion_protection    = true
  parameter_group_name   = aws_db_parameter_group.rds_parameter_group.name
  vpc_security_group_ids = [aws_security_group.rds_security_group.id]
}
resource "aws_db_parameter_group" "rds_parameter_group" {
  name   = "example-app-staging-20251111201901-parameters"
  family = "postgres17"

  parameter {
    name  = "log_min_duration_statement"
    value = "1000"
  }
}

output "example_app_rds" {
  value = {
    address    = aws_db_instance.rds_database.address
    identifier = aws_db_instance.rds_database.identifier
  }
  sensitive = true
}

module "example_app_rds_app_user" {
  source = "../../modules/postgresql_app_user"

  host         = "rds-staging.example.test"
  app_username = "example_app_app"
  rds_instance = aws_db_instance.rds_database
}

output "example_app_rds_app_username" {
  value = module.example_app_rds_app_user.app_username
}
"""

LAYOUT = TerraformLayout(
    dir=Path("."),
    blue_file="example_app_rds_instance.tf",
    green_file="example_app_rds_green.tf",
    old_file="example_app_rds_old.tf",
    instance="rds_database",
    parameter_group="rds_parameter_group",
    app_user_module="example_app_rds_app_user",
    app_user_toggle="enabled",
    state_command="state resources staging",
)
TODAY = datetime.date(2026, 10, 16)
GREEN_ID = "example-app-staging-20261016120000"


def make_green(**kw) -> str:
    args = dict(
        green_id=GREEN_ID,
        green_host="rds-green-staging.example.test",
        engine_version="17.11",
        storage_type="gp3",
        settings=["multi_az = false"],
        today=TODAY,
        config_name="db_cutover.toml",
    )
    args.update(kw)
    return tf.green_file(BLUE, LAYOUT, **args)


def attr(block: str, name: str) -> str | None:
    return tf.get_attr(block, name)


def test_green_file() -> None:
    green = make_green()
    inst = tf.take_block(green, tf.resource_header("aws_db_instance", "rds_database_green"))
    assert attr(inst, "identifier") == f'"{GREEN_ID}"'
    assert attr(inst, "engine_version") == '"17.11"'
    assert attr(inst, "storage_type") == '"gp3"'
    assert attr(inst, "multi_az") == "false"
    assert attr(inst, "parameter_group_name") == "aws_db_parameter_group.rds_parameter_group_green.name"
    assert attr(inst, "instance_class") == '"db.t4g.small"'  # BLUE's settings carry over
    assert attr(inst, "password") == 'local.db_op_fields["example_app_rds_admin_password"]'

    params = tf.take_block(green, tf.resource_header("aws_db_parameter_group", "rds_parameter_group_green"))
    assert attr(params, "name") == f'"{GREEN_ID}-parameters"'
    assert attr(params, "family") == '"postgres17"'
    assert "log_min_duration_statement" in params  # BLUE's parameters carry over
    assert '"rds.logical_replication"' in params
    assert params.count("{") == params.count("}")

    module = tf.take_block(green, tf.module_header("example_app_rds_app_user_green"))
    assert attr(module, "host") == '"rds-green-staging.example.test"'
    assert attr(module, "rds_instance") == "aws_db_instance.rds_database_green"
    assert attr(module, "enabled") == "false"
    assert 'output "green_rds"' in green
    # Nothing in GREEN's file may still point at BLUE's resources.
    assert not re.search(r"aws_db_instance\.rds_database\b(?!_green)", green)
    assert not re.search(r"aws_db_parameter_group\.rds_parameter_group\b(?!_green)", green)


def test_family_follows_major_version() -> None:
    green = make_green(engine_version="18.1")
    params = tf.take_block(green, tf.resource_header("aws_db_parameter_group", "rds_parameter_group_green"))
    assert attr(params, "family") == '"postgres18"'


def test_logical_replication_not_duplicated() -> None:
    blue = BLUE.replace(
        '    value = "1000"\n  }\n',
        '    value = "1000"\n  }\n  parameter {\n    name  = "rds.logical_replication"\n    value = "1"\n  }\n',
    )
    green = tf.green_file(
        blue, LAYOUT, green_id=GREEN_ID, green_host=None, engine_version="17.11", today=TODAY, config_name="x"
    )
    assert green.count("rds.logical_replication") == 1


def test_promote_files() -> None:
    green = make_green()
    # Simulate the operator switching the module on after copy-schema.
    green = green.replace("  enabled = false", "  enabled = true")
    primary, old = tf.promote_files(BLUE, green, LAYOUT, primary_host="rds-staging.example.test", today=TODAY)

    inst = tf.take_block(primary, tf.resource_header("aws_db_instance", "rds_database"))
    assert attr(inst, "identifier") == f'"{GREEN_ID}"'
    assert attr(inst, "parameter_group_name") == "aws_db_parameter_group.rds_parameter_group.name"
    params = tf.take_block(primary, tf.resource_header("aws_db_parameter_group", "rds_parameter_group"))
    assert attr(params, "name") == f'"{GREEN_ID}-parameters"'
    module = tf.take_block(primary, tf.module_header("example_app_rds_app_user"))
    assert attr(module, "host") == '"rds-staging.example.test"'
    assert attr(module, "rds_instance") == "aws_db_instance.rds_database"
    assert attr(module, "enabled") is None
    assert tf.TOGGLE_COMMENT not in primary
    assert "_green" not in primary
    assert "Generated by db_cutover_orchestrator" not in primary
    assert 'output "example_app_rds"' in primary and 'output "example_app_rds_app_username"' in primary

    old_inst = tf.take_block(old, tf.resource_header("aws_db_instance", "rds_database_old"))
    assert attr(old_inst, "identifier") == '"example-app-staging-20251111201901"'
    assert attr(old_inst, "parameter_group_name") == "aws_db_parameter_group.rds_parameter_group_old.name"
    old_params = tf.take_block(old, tf.resource_header("aws_db_parameter_group", "rds_parameter_group_old"))
    assert attr(old_params, "name") == '"example-app-staging-20251111201901-parameters"'
    assert "module" not in old
    assert 'output "old_rds"' in old


def test_state_commands() -> None:
    assert tf.state_commands(LAYOUT) == [
        "state resources staging rm module.example_app_rds_app_user",
        "state resources staging mv aws_db_instance.rds_database aws_db_instance.rds_database_old",
        "state resources staging mv aws_db_parameter_group.rds_parameter_group "
        "aws_db_parameter_group.rds_parameter_group_old",
        "state resources staging mv aws_db_instance.rds_database_green aws_db_instance.rds_database",
        "state resources staging mv aws_db_parameter_group.rds_parameter_group_green "
        "aws_db_parameter_group.rds_parameter_group",
        "state resources staging mv module.example_app_rds_app_user_green module.example_app_rds_app_user",
    ]


def test_set_attr_ignores_nested_blocks() -> None:
    block = 'resource "x" "y" {\n  parameter {\n    name = "inner"\n  }\n  name = "outer"\n}\n'
    out = tf.set_attr(block, "name", '"new"')
    assert '    name = "inner"' in out and 'name = "new"' in out and '"outer"' not in out


def test_set_attr_adds_missing() -> None:
    out = tf.set_attr('resource "x" "y" {\n  a = 1\n}\n', "b", "2")
    assert out == 'resource "x" "y" {\n  a = 1\n  b = 2\n}\n'


def test_missing_block() -> None:
    with pytest.raises(ValueError, match="no block"):
        tf.take_block(BLUE, tf.resource_header("aws_db_instance", "nope"))
